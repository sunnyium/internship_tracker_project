"""Reading job rows out of a machine-readable listings file.

    parse() | every active posting in a listings.json style document

The Simplify schema and the copies of it that other repos maintain are the
only structured thing in this half of the project, and they carry fields the
markdown tables can't: an `active` flag, real posting timestamps, a sponsorship
note, and a degrees list. All of that survives into the job dict so the filters
can use it.

Field names still drift between forks, so every field is looked up through a
list of aliases rather than by its Simplify name. Anything unrecognized is
ignored rather than fatal - these files are generated by other people's
tooling and grow columns without warning.
"""

import json

from github_boards import normalize

FIELD_ALIASES = {
    "company": ("company_name", "company", "employer", "organization", "org"),
    "title": ("title", "position", "role", "job_title", "name"),
    "url": ("url", "link", "apply_link", "application_link", "absolute_url", "job_url"),
    "location": ("locations", "location", "city", "office"),
    "posted_at": ("date_posted", "posted_at", "date_updated", "created_at", "updated_at"),
    "term": ("terms", "term", "season", "cycle"),
    "sponsorship": ("sponsorship", "visa", "work_authorization"),
    "degrees": ("degrees", "degree", "education"),
    "category": ("category", "type", "field"),
}

# Both have to be true when present. Simplify sets active=false the moment a
# role closes and is_visible=false for entries pulled from the public list.
VISIBILITY_FIELDS = ("active", "is_visible")


def parse(text, repo_name=""):
    """Every active posting in a listings file. Raises on malformed JSON -
    a file that stopped being JSON is a broken source, not an empty one."""
    payload = json.loads(text)
    if isinstance(payload, dict):
        # Some forks wrap the array; take the first list-valued key.
        payload = next((v for v in payload.values() if isinstance(v, list)), [])
    if not isinstance(payload, list):
        return []

    jobs = []
    for entry in payload:
        if not isinstance(entry, dict):
            continue
        if any(entry.get(f) is False for f in VISIBILITY_FIELDS):
            continue
        job = _entry_to_job(entry)
        if job:
            jobs.append(job)
    return jobs


def _first(entry, field):
    for key in FIELD_ALIASES[field]:
        if key in entry and entry[key] not in (None, "", [], {}):
            return entry[key]
    return None


def _as_text(value):
    """Lists become "a, b" - locations and terms arrive both ways."""
    if isinstance(value, (list, tuple, set)):
        return ", ".join(str(v) for v in value if v)
    return "" if value is None else str(value)


def _entry_to_job(entry):
    title = _as_text(_first(entry, "title")).strip()
    url = _as_text(_first(entry, "url")).strip()
    if not title or not url:
        return None

    posted = _first(entry, "posted_at")
    return {
        "company": _as_text(_first(entry, "company")).strip(),
        "title": title,
        "location": _as_text(_first(entry, "location")),
        "url": url,
        "posted_at": normalize.from_epoch(posted) or normalize.parse_date(posted),
        "term": _as_text(_first(entry, "term")),
        "notes": _as_text(_first(entry, "degrees")),
        "category": _as_text(_first(entry, "category")),
        "sponsorship": _as_text(_first(entry, "sponsorship")),
    }
